/**
 * Returns stored equipment from localStorage or seeds initialEquipment.
 */
export function getStoredEquipment(): EquipmentItem[] {
  const stored = localStorage.getItem(INVENTORY_STORAGE_KEY);
  if (stored) {
    try {
      const parsed = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    } catch {
      // fallback
    }
  }
  localStorage.setItem(INVENTORY_STORAGE_KEY, JSON.stringify(initialEquipment));
  return initialEquipment;
}

/**
 * Updates a single equipment's status in the local store.
 */
export function updateStoredEquipment(
  id: string,
  updates: Partial<EquipmentItem>,
): EquipmentItem {
  const list = getStoredEquipment();
  const index = list.findIndex((item) => item.id === id);
  if (index === -1) {
    throw new Error(`Equipment item with ID ${id} not found.`);
  }

  const updatedItem: EquipmentItem = {
    ...list[index],
    ...updates,
    last_maintenance:
      updates.status === 'MAINTENANCE' || updates.status === 'OPERATIONAL'
        ? new Date().toISOString().split('T')[0]
        : list[index].last_maintenance,
  };

  list[index] = updatedItem;
  localStorage.setItem(INVENTORY_STORAGE_KEY, JSON.stringify(list));
  return updatedItem;
}

/**
 * Generates the full InventoryDashboardPayload using stored equipment.
 */
export function getFallbackInventoryDashboard(params?: {
  status?: string;
  lab_code?: string;
  category?: string;
  search?: string;
}): InventoryDashboardPayload {
  const allEquipment = getStoredEquipment();

  let filtered = allEquipment;
  if (params?.status && params.status !== 'ALL') {
    filtered = filtered.filter((e) => e.status === params.status);
  }
  if (params?.lab_code && params.lab_code !== 'ALL') {
    filtered = filtered.filter((e) => e.lab_code === params.lab_code);
  }
  if (params?.category && params.category !== 'ALL') {
    filtered = filtered.filter((e) => e.category === params.category);
  }
  if (params?.search && params.search.trim()) {
    const q = params.search.toLowerCase().trim();
    filtered = filtered.filter(
      (e) =>
        e.equipment_name.toLowerCase().includes(q) ||
        e.serial_number.toLowerCase().includes(q) ||
        e.asset_tag.toLowerCase().includes(q) ||
        e.brand.toLowerCase().includes(q) ||
        e.lab_code.toLowerCase().includes(q),
    );
  }

  const opCount = allEquipment.filter((e) => e.status === 'OPERATIONAL').length;
  const inUseCount = allEquipment.filter((e) => e.status === 'IN_USE').length;
  const maintCount = allEquipment.filter((e) => e.status === 'MAINTENANCE').length;
  const offCount = allEquipment.filter(
    (e) => e.status === 'OFFLINE' || e.status === 'PARTIALLY_WRITTEN_OFF',
  ).length;

  const totalInv = initialBatches.reduce((sum, b) => sum + (b.total_cost || 0), 0);

  const status_breakdown: Record<string, number> = {
    OPERATIONAL: opCount,
    IN_USE: inUseCount,
    MAINTENANCE: maintCount,
    OFFLINE: offCount,
  };

  const category_breakdown: Record<string, number> = {};
  allEquipment.forEach((e) => {
    category_breakdown[e.category] = (category_breakdown[e.category] || 0) + 1;
  });

  const lab_breakdown: Record<string, number> = {};
  allEquipment.forEach((e) => {
    lab_breakdown[e.lab_code] = (lab_breakdown[e.lab_code] || 0) + 1;
  });

  return {
    success: true,
    timestamp: new Date().toISOString(),
    summary: {
      total_equipment: allEquipment.length,
      operational_count: opCount,
      in_use_count: inUseCount,
      maintenance_count: maintCount,
      offline_count: offCount,
      total_batches: initialBatches.length,
      total_models: initialModels.length,
      total_labs: initialLabsSummary.length,
      total_investment_formatted: '₹1,48,50,000.00',
      total_investment: totalInv || 14850000,
      status_breakdown,
      category_breakdown,
      lab_breakdown,
    },
    equipment: filtered,
    batches: initialBatches,
    models: initialModels,
    labs: initialLabsSummary,
  };
}

